import axios from 'axios';

const API_URL = import.meta.env.VITE_API_URL || '/api';

const api = axios.create({
  baseURL: API_URL,
  headers: {
    'Content-Type': 'application/json',
  },
});

export const generateQuestion = async (role, difficulty, previousQuestions = []) => {
  try {
    const response = await api.post('/generate-question', { role, difficulty, previousQuestions });
    return response.data;
  } catch (error) {
    if (error.response && error.response.data && error.response.data.error) {
      throw new Error(error.response.data.error);
    }
    throw error;
  }
};

export const evaluateAnswer = async (role, question, answer) => {
  try {
    const response = await api.post('/evaluate-answer', { role, question, answer });
    return response.data;
  } catch (error) {
    if (error.response && error.response.data && error.response.data.error) {
      throw new Error(error.response.data.error);
    }
    throw error;
  }
};

export default api;
